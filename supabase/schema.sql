-- 악보를 지우면 모든 콘티에서도 자동으로 빠지게
create or replace function public.remove_score_from_setlists()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.setlists s
     set items = coalesce((select jsonb_agg(e) from jsonb_array_elements(s.items) e
                           where (e ->> 'score_id')::bigint is distinct from old.id), '[]'::jsonb)
   where s.items @> jsonb_build_array(jsonb_build_object('score_id', old.id));
  return old;
end $$;

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'scores_remove_from_setlists') then
    create trigger scores_remove_from_setlists after delete on public.scores
      for each row execute function public.remove_score_from_setlists();
  end if;
end $$;

-- 기존에 날짜를 붙여 올린 악보가 있으면 그 날짜의 콘티로 옮김
insert into public.setlists (worship_date, items)
select x.worship_date, jsonb_agg(jsonb_build_object('score_id', x.id) order by x.sort_order, x.title)
  from public.scores x
 where x.worship_date is not null
   and not exists (select 1 from public.setlists s where s.worship_date = x.worship_date)
 group by x.worship_date;

