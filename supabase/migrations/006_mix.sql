-- =====================================================================
--  006: 나눔 조 나누기 (실시간 미니게임)
--   - 누군가 방을 열면(4자리 참가 코드) 현장에 있는 사람들이 휴대폰으로 참가
--   - 방장이 조 개수를 정해 "조 나누기"를 누르면 모두의 화면에 결과가 동시에 뜸
--   - 로그인 안 한 방문자도 이름만 적고 참가 가능 (토큰으로 본인 확인하는 함수 사용)
--  (여러 번 실행해도 안전)
-- =====================================================================

create table if not exists public.mix_rooms (
  id          uuid primary key default gen_random_uuid(),
  code        text not null check (code ~ '^[0-9]{4}$'),
  title       text not null default '나눔 조 나누기' check (char_length(title) <= 60),
  host_id     uuid references public.profiles(id) on delete set null,
  status      text not null default 'open' check (status in ('open', 'done', 'closed')),
  group_count int  not null default 3 check (group_count between 1 and 50),
  groups      jsonb not null default '[]'::jsonb,   -- [{no, name, color, ids:[member id]}]
  round       int  not null default 0,               -- 조를 나눌 때마다 +1 (화면 애니메이션 신호)
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create unique index if not exists mix_rooms_open_code on public.mix_rooms (code) where status <> 'closed';
create index if not exists mix_rooms_created_idx on public.mix_rooms (created_at desc);

create table if not exists public.mix_members (
  id            bigint generated by default as identity primary key,
  room_id       uuid not null references public.mix_rooms(id) on delete cascade,
  user_id       uuid references public.profiles(id) on delete cascade,   -- 비어 있으면 방문자·직접 추가
  name          text not null check (char_length(btrim(name)) between 1 and 30),
  is_leader     boolean not null default false,
  added_by_host boolean not null default false,
  created_at    timestamptz not null default now()
);
create unique index if not exists mix_members_room_user on public.mix_members (room_id, user_id) where user_id is not null;
create index if not exists mix_members_room_idx on public.mix_members (room_id, created_at);

-- 방문자 본인 확인용 토큰 (아무도 직접 읽을 수 없음, 함수로만 사용)
create table if not exists public.mix_guest_tokens (
  member_id bigint primary key references public.mix_members(id) on delete cascade,
  token     uuid not null
);

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'mix_rooms_touch') then
    create trigger mix_rooms_touch before update on public.mix_rooms
      for each row execute function public.touch_updated_at();
  end if;
end $$;

alter table public.mix_rooms enable row level security;
alter table public.mix_members enable row level security;
alter table public.mix_guest_tokens enable row level security;
revoke all on public.mix_guest_tokens from anon, authenticated;

do $$ begin
  -- 방: 성도(승인된 회원)는 볼 수 있고, 누구나 열 수 있음. 바꾸기·지우기는 방장과 관리자
  if not exists (select 1 from pg_policy where polname = 'mix rooms: member read') then
    create policy "mix rooms: member read" on public.mix_rooms for select using (public.is_member());
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix rooms: member open') then
    create policy "mix rooms: member open" on public.mix_rooms for insert with check (public.is_member() and host_id = auth.uid());
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix rooms: host update') then
    create policy "mix rooms: host update" on public.mix_rooms for update
      using (host_id = auth.uid() or public.is_admin()) with check (host_id = auth.uid() or public.is_admin());
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix rooms: host delete') then
    create policy "mix rooms: host delete" on public.mix_rooms for delete using (host_id = auth.uid() or public.is_admin());
  end if;

  -- 참가자: 성도는 볼 수 있음. 본인 참가·나가기, 방장은 이름 추가·조장 지정·빼기
  if not exists (select 1 from pg_policy where polname = 'mix members: member read') then
    create policy "mix members: member read" on public.mix_members for select using (public.is_member());
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix members: join or host add') then
    create policy "mix members: join or host add" on public.mix_members for insert with check (
      (user_id = auth.uid() and public.is_member() and added_by_host = false and is_leader = false
         and exists (select 1 from public.mix_rooms r where r.id = room_id and r.status <> 'closed'))
      or exists (select 1 from public.mix_rooms r where r.id = room_id and (r.host_id = auth.uid() or public.is_admin()))
    );
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix members: host update') then
    create policy "mix members: host update" on public.mix_members for update
      using (exists (select 1 from public.mix_rooms r where r.id = room_id and (r.host_id = auth.uid() or public.is_admin())))
      with check (exists (select 1 from public.mix_rooms r where r.id = room_id and (r.host_id = auth.uid() or public.is_admin())));
  end if;
  if not exists (select 1 from pg_policy where polname = 'mix members: leave or host remove') then
    create policy "mix members: leave or host remove" on public.mix_members for delete using (
      user_id = auth.uid()
      or exists (select 1 from public.mix_rooms r where r.id = room_id and (r.host_id = auth.uid() or public.is_admin()))
    );
  end if;
end $$;

-- 방문자 참가 (로그인 없이 이름만)
create or replace function public.mix_guest_join(p_code text, p_name text)
returns json language plpgsql security definer set search_path = public as $$
declare r public.mix_rooms; m_id bigint; tok uuid := gen_random_uuid(); n int;
begin
  p_name := btrim(coalesce(p_name, ''));
  if char_length(p_name) < 1 or char_length(p_name) > 20 then raise exception '이름을 1~20자로 적어 주세요.'; end if;
  select * into r from public.mix_rooms where code = btrim(coalesce(p_code, '')) and status <> 'closed' order by created_at desc limit 1;
  if r.id is null then raise exception '참가 코드를 찾을 수 없어요. 숫자 4자리를 다시 확인해 주세요.'; end if;
  select count(*) into n from public.mix_members where room_id = r.id;
  if n >= 300 then raise exception '참가 인원이 너무 많아요.'; end if;
  insert into public.mix_members (room_id, name) values (r.id, p_name) returning id into m_id;
  insert into public.mix_guest_tokens (member_id, token) values (m_id, tok);
  return json_build_object('room_id', r.id, 'code', r.code, 'member_id', m_id, 'token', tok);
end $$;

-- 방문자 화면 상태 (본인 토큰이 맞을 때만)
create or replace function public.mix_guest_state(p_member_id bigint, p_token uuid)
returns json language sql stable security definer set search_path = public as $$
  select json_build_object(
    'room', json_build_object('id', r.id, 'code', r.code, 'title', r.title, 'status', r.status, 'group_count', r.group_count,
                              'groups', r.groups, 'round', r.round, 'host_id', r.host_id, 'created_at', r.created_at, 'updated_at', r.updated_at),
    'me', m.id,
    'members', (select coalesce(json_agg(json_build_object('id', x.id, 'name', x.name, 'is_leader', x.is_leader, 'user_id', x.user_id,
                                                           'added_by_host', x.added_by_host, 'created_at', x.created_at) order by x.created_at, x.id), '[]'::json)
                  from public.mix_members x where x.room_id = r.id))
    from public.mix_guest_tokens t
    join public.mix_members m on m.id = t.member_id
    join public.mix_rooms r on r.id = m.room_id
   where t.member_id = p_member_id and t.token = p_token;
$$;

create or replace function public.mix_guest_leave(p_member_id bigint, p_token uuid)
returns void language sql security definer set search_path = public as $$
  delete from public.mix_members m using public.mix_guest_tokens t
   where t.member_id = m.id and m.id = p_member_id and t.token = p_token;
$$;

revoke all on function public.mix_guest_join(text, text) from public;
revoke all on function public.mix_guest_state(bigint, uuid) from public;
revoke all on function public.mix_guest_leave(bigint, uuid) from public;
grant execute on function public.mix_guest_join(text, text) to anon, authenticated;
grant execute on function public.mix_guest_state(bigint, uuid) to anon, authenticated;
grant execute on function public.mix_guest_leave(bigint, uuid) to anon, authenticated;

