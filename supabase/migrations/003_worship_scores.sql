-- 1) 회원의 소속 팀 (예: {'worship'} = 찬양팀). 관리자만 바꿀 수 있음
alter table public.profiles
  add column if not exists teams text[] not null default '{}';

create or replace function public.in_team(t text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and status = 'active' and (role = 'admin' or t = any(teams))
  );
$$;

create or replace function public.guard_profile_update()
returns trigger language plpgsql security invoker set search_path = public as $$
begin
  if public.is_app_user() and not public.is_admin() then
    new.role := old.role;
    new.teams := old.teams;
    if new.status is distinct from old.status and new.status <> 'withdrawn' then
      new.status := old.status;
    end if;
    new.email := old.email;
  end if;
  return new;
end $$;

-- 2) 악보
create table if not exists public.scores (
  id           bigint generated by default as identity primary key,
  title        text not null,
  artist       text,
  song_key     text,
  memo         text,
  worship_date date,                 -- 콘티 날짜 (비우면 '전체 악보'에만)
  sort_order   integer not null default 0,
  file_path    text not null,        -- 비공개 버킷 'scores' 안의 경로
  file_name    text,
  file_size    integer,
  page_count   integer,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists scores_date_idx on public.scores (worship_date desc nulls last, sort_order);

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'scores_touch') then
    create trigger scores_touch before update on public.scores
      for each row execute function public.touch_updated_at();
  end if;
end $$;

alter table public.scores enable row level security;

do $$ begin
  if not exists (select 1 from pg_policy where polname = 'scores: team read') then
    create policy "scores: team read" on public.scores for select using (public.in_team('worship'));
  end if;
  if not exists (select 1 from pg_policy where polname = 'scores: admin write') then
    create policy "scores: admin write" on public.scores for all using (public.is_admin()) with check (public.is_admin());
  end if;
end $$;

-- 3) 비공개 저장소 'scores' (찬양팀·관리자만 읽기, 관리자만 올리기)
insert into storage.buckets (id, name, public)
values ('scores', 'scores', false)
on conflict (id) do update set public = false;

do $$ begin
  if not exists (select 1 from pg_policy where polname = 'scores files: team read') then
    create policy "scores files: team read" on storage.objects
      for select using (bucket_id = 'scores' and public.in_team('worship'));
  end if;
  if not exists (select 1 from pg_policy where polname = 'scores files: admin insert') then
    create policy "scores files: admin insert" on storage.objects
      for insert with check (bucket_id = 'scores' and public.is_admin());
  end if;
  if not exists (select 1 from pg_policy where polname = 'scores files: admin update') then
    create policy "scores files: admin update" on storage.objects
      for update using (bucket_id = 'scores' and public.is_admin());
  end if;
  if not exists (select 1 from pg_policy where polname = 'scores files: admin delete') then
    create policy "scores files: admin delete" on storage.objects
      for delete using (bucket_id = 'scores' and public.is_admin());
  end if;
end $$;

-- 4) 모든 업로드는 관리자만: 성도 사진 업로드 정책을 관리자 전용으로 변경
alter policy "media: member upload own folder" on storage.objects
  with check (bucket_id = 'media' and public.is_admin());
