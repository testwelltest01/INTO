-- 악보: PDF 파일 또는 페이지 이미지 목록(여러 곡 PDF를 나눠 저장한 경우)
alter table public.scores alter column file_path drop not null;
alter table public.scores add column if not exists pages jsonb not null default '[]'::jsonb;

-- 콘티: 날짜별 곡 순서. items = [{ "score_id": 12, "key": "A", "memo": "후렴 2번" }, ...]
create table if not exists public.setlists (
  id           bigint generated by default as identity primary key,
  worship_date date not null,
  title        text,
  memo         text,
  items        jsonb not null default '[]'::jsonb,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists setlists_date_idx on public.setlists (worship_date desc);

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'setlists_touch') then
    create trigger setlists_touch before update on public.setlists
      for each row execute function public.touch_updated_at();
  end if;
end $$;

alter table public.setlists enable row level security;
do $$ begin
  if not exists (select 1 from pg_policy where polname = 'setlists: team read') then
    create policy "setlists: team read" on public.setlists for select using (public.in_team('worship'));
  end if;
  if not exists (select 1 from pg_policy where polname = 'setlists: admin write') then
    create policy "setlists: admin write" on public.setlists for all using (public.is_admin()) with check (public.is_admin());
  end if;
end $$;

-- 악보를 지우면 모든 콘티에서도 자동으로 빠지게
create or replace function public.remove_score_from_setlists()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update public.setlists s
     set items = coalesce((select jsonb_agg(e) from jsonb_array_elements(s.items) e
                           where (e ->> 'score_id')::bigint is distinct from old.id), '[]'::jsonb)
   where s.items @> jsonb_build_array(jsonb_build_object('score_id', old.id));
  return old;
end $$;

do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'scores_remove_from_setlists') then
    create trigger scores_remove_from_setlists after delete on public.scores
      for each row execute function public.remove_score_from_setlists();
  end if;
end $$;

-- 기존에 날짜를 붙여 올린 악보가 있으면 그 날짜의 콘티로 옮김
insert into public.setlists (worship_date, items)
select x.worship_date, jsonb_agg(jsonb_build_object('score_id', x.id) order by x.sort_order, x.title)
  from public.scores x
 where x.worship_date is not null
   and not exists (select 1 from public.setlists s where s.worship_date = x.worship_date)
 group by x.worship_date;
